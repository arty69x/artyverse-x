import { theme } from "../shared/schema.ts";
import { designSystem } from "../shared/design.ts";
import { writeFileSync } from "node:fs";
writeFileSync(
  "DESIGN_TOKENS.json",
  JSON.stringify({ legacyAdapter: theme, ...designSystem }, null, 2) + "\n",
);
writeFileSync(
  "src/tokens.css",
  ":root{" +
    Object.entries(theme.primitive)
      .map(([k, v]) => "--" + k + ":" + v)
      .join(";") +
    "}\n",
);
const names = {
  background: "bg",
  lineStrong: "line-strong",
  onAccent: "on-accent",
};
let css = "/* Generated by npm run tokens from shared/design.ts */\n";
for (const [name, tokens] of Object.entries(designSystem.themes))
  css +=
    `html[data-theme="${name}"]{` +
    Object.entries(tokens)
      .map(([k, v]) => `--${names[k] || k}:${v}`)
      .join(";") +
    ";--background:var(--bg);--border:var(--line);--elevated:var(--surface2)}\n";
css +=
  ':root{--font-display:"Syne Variable",PlexThai,sans-serif;--font-body:"DM Sans",PlexThai,sans-serif;--font-mono:"JetBrains Mono",monospace;--radius-card:18px;--radius:18px;--brand-lime:' +
  designSystem.brand.lime +
  ";--brand-pink:" +
  designSystem.brand.pink +
  ";--brand-cyan:" +
  designSystem.brand.cyan +
  ";--brand-violet:" +
  designSystem.brand.violet +
  ";--motion-micro:120ms;--motion-panel:320ms;--motion-scene:500ms}\n";
writeFileSync("src/v3/tokens.css", css);
